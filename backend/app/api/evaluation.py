import json

from fastapi import APIRouter, Depends, Query

from app.core.security import require_roles
from app.core.settings import settings
from app.models import Role, User
from app.pipeline.train import DEFAULT_MODEL_ID
from app.schemas.evaluation import EvaluationMetricsOut

router = APIRouter(prefix="/evaluation", tags=["evaluation"])


def _read_json(name: str) -> dict | None:
    path = settings.results_dir / f"{name}.json"
    if not path.exists():
        return None
    return json.loads(path.read_text(encoding="utf-8"))


@router.get("/metrics", response_model=EvaluationMetricsOut)
def get_metrics(
    model_id: str = Query(default=DEFAULT_MODEL_ID, alias="modelId"),
    persistence: str | None = Query(default=None, pattern="^(on|off)$"),
    _user: User = Depends(require_roles(Role.EVALUATOR, Role.ADMINISTRATOR)),
):
    """REQ-5 (persistence unset) / REQ-11 (persistence=on|off): served from the reports
    generated by `python -m app.evaluation.baseline` / `.reports` (see their docstrings)."""
    if persistence is None:
        report = _read_json("phase2_baseline")
        if report is None or report.get("model_id") != model_id:
            return EvaluationMetricsOut(
                available=False,
                model_id=model_id,
                message=(
                    "No baseline report yet. Run: python -m app.evaluation.baseline "
                    "--out docs/results/phase2_baseline"
                ),
            )
        overall = report["overall"]
        return EvaluationMetricsOut(
            available=True,
            model_id=model_id,
            persistence=None,
            channels_evaluated=report["channels_evaluated"],
            precision=overall["precision"],
            recall=overall["recall"],
            f1=overall["f1"],
            point_fpr=overall["point_fpr"],
        )

    report = _read_json("phase3_persistence_comparison")
    if report is None:
        return EvaluationMetricsOut(
            available=False,
            model_id=model_id,
            persistence=persistence,
            message=(
                "No persistence-filter comparison yet. Run: python -m app.evaluation.reports "
                "--model-id " + model_id + " --out docs/results/phase3_persistence_comparison"
            ),
        )
    metrics = report["comparison"]["with_filter" if persistence == "on" else "without_filter"]
    return EvaluationMetricsOut(
        available=True,
        model_id=model_id,
        persistence=persistence,
        channels_evaluated=len(report["channels"]),
        precision=metrics["precision"],
        recall=metrics["recall"],
        f1=metrics["f1"],
        point_fpr=metrics["point_fpr"],
    )
